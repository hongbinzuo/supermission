let currentLocale: Locale = "en";

export function setLocale(locale: Locale): void {
  currentLocale = locale;
}

export function getLocale(): Locale {
  return currentLocale;
}

export function t(key: string): string {
  return messages[currentLocale]?.[key] ?? messages.en[key] ?? key;
}

export async function loadLocaleFromConfig(repo: string): Promise<void> {
  try {
    const configPath = join(repo, WORK_ROOT, "config.yaml");
    const text = await readFile(configPath, "utf8");
    const match = /locale:\s*(\w+)/.exec(text);
    if (match && match[1] && isValidLocale(match[1])) {
      currentLocale = match[1] as Locale;
    }
  } catch {
    // No config file or no locale setting — use default (en)
    // Also check SUPERMISSION_LOCALE env var
    const envLocale = process.env.SUPERMISSION_LOCALE;
    if (envLocale && isValidLocale(envLocale)) {
      currentLocale = envLocale as Locale;
    }
  }
}

function isValidLocale(value: string): boolean {
  return ["en", "zh", "ja", "ko", "es", "fr", "de"].includes(value);
}
